// ------------------------------------------------------------------------------- rooms
// A part of the map with a name, made of boxes (world space).
struct Room {
    std::string name;
    std::vector<AABB> boxes;
    AABB bounds;          // of all boxes
    std::string source;   // where it came from ("nav place", "file", "soundscape ...")
    bool contains(const Vec3& p) const;
    void addBox(const AABB& b) {
        boxes.push_back(b);
        bounds.add(b.mins);
        bounds.add(b.maxs);
    }
};

// Rooms from a rooms file (scripts/ghosthunt/rooms/<map>.txt):
//   "Rooms" { "room" { "name" "Kitchen" "box" "minx miny minz maxx maxy maxz" "box" "..." } }
std::vector<Room> parseRooms(std::string_view text, std::string* error = nullptr);
std::string writeRooms(const std::vector<Room>& rooms, std::string_view comment);
// The index of the room holding `p` (the smallest one if several do), or -1.
int roomAt(const std::vector<Room>& rooms, const Vec3& p);

// Guesses rooms from the map's soundscape entities: each env_soundscape(_proxy) is placed in
// a part of the map that sounds alike, so the walls around it (found by tracing from it,
// limited by its radius) make a room; a trigger_soundscape's brush is a room as it is. A room
// is named after the soundscape's position targets inside it (sound sources such as
// "bathrooms"), else after the soundscape. Boxes that mostly repeat an earlier one are dropped.
std::vector<Room> guessRoomsFromSoundscapes(World& world);

// --------------------------------------------------------------------------- nav mesh
// Walkable areas and how they connect: the map's .nav areas, or a grid generated by walking
// the map from its spawn points when there is no .nav.
class NavMesh {
public:
    std::vector<nav::Area> areas;
    std::vector<std::vector<int>> links;  // per area: indices of areas it leads to
    std::vector<std::string> places;      // names for nav::Area::place
    std::string source;                   // "maps/x.nav" or "generated"

    void fromNav(const nav::NavFile& file);
    // Flood fill on a grid of `cell` units from `seeds` (floor positions), with a player
    // sized box stepping up to 18 units and dropping up to 64. At most `maxAreas` cells.
    void generate(World& world, const std::vector<Vec3>& seeds, float cell = 32, size_t maxAreas = 40000);
    // The area whose floor is at or just below `p`, else the closest one within 256 units; -1.
    int findArea(const Vec3& p) const;
    // A* over the areas: points from `start` to `goal` through the edges between areas.
    bool findPath(const Vec3& start, const Vec3& goal, std::vector<Vec3>& points) const;
    // Areas overlapping a box (for debug drawing).
    void areasNear(const Vec3& p, float radius, std::vector<int>& out) const;
    size_t linkCount() const;

private:
    void buildIndex();
    static constexpr float kBucket = 256;
    std::unordered_map<int64_t, std::vector<int>> buckets_;
    static int64_t bucketKey(int x, int y) { return (int64_t(x) << 32) ^ int64_t(uint32_t(y)); }
};

// --------------------------------------------------------------------------------- EMF
// Something the ghost did leaves an electromagnetic trace for a while: level 2 when it
// touched something, 3 when it threw something, 5 (evidence, only some ghosts) instead of 3.
struct EmfSource {
    Vec3 pos;
    Entity follow;  // a thrown prop carries its trace with it
    int level = 2;
    double start = 0, end = 0;
    std::string cause;
};

struct EmfField {
    std::vector<EmfSource> sources;
    void add(const EmfSource& s) { sources.push_back(s); }
    void update(World& world);  // moves following sources, drops expired ones
    // What a reader at `p` shows: 1 (nothing) to 5, the strongest source within `range`.
    int reading(const Vec3& p, float range, const EmfSource** strongest = nullptr) const;
};

// ------------------------------------------------------------------------------- ghost
struct Ghost {
    enum class State { Idle, Wander, Roam, Return };
    State state = State::Idle;
    double stateUntil = 0;
    int room = -1;  // favourite room (index into Hunt::rooms)
    bool emf5 = false;
    std::vector<Vec3> path;
    size_t pathIndex = 0;
    Vec3 goal;
    double nextThrow = 0, nextTouch = 0;
    std::string lastEvent;
    double lastEventTime = -1;
};
const char* stateName(Ghost::State s);

// A throw, kept for debug drawing.
struct ThrowRecord {
    Entity prop;
    std::string model;
    Vec3 ghostPos, propStart, velocity;
    double time = 0;
    int emfLevel = 0;
    std::vector<Vec3> trail;  // the prop's centre for a few seconds
};

// ------------------------------------------------------------------------------- hunt
// Everything the game keeps per World.
struct Hunt {
    explicit Hunt(World& w) : world(w) {}
    World& world;
    std::string map;  // map name without directory and extension
    NavMesh nav;
    std::vector<Room> rooms;
    std::vector<std::vector<int>> roomAreas;  // per room: nav areas in it
    std::vector<int> areaRoom;                // per nav area: room or -1
    Entity ghost;
    EmfField emf;
    std::vector<ThrowRecord> throws;
    std::mt19937 rng{1};

    void loadNav();
    // gh_rooms_source: auto (file, else nav places, else soundscapes), file, nav or soundscape.
    void loadRooms(std::string_view source);
    void assignAreasToRooms();
    Ghost* ghostState();
    Vec3 ghostPos();
};

// The hunt of a World (null when the game is not running there), and of the most recently
// started World (for console commands).
Hunt* huntOf(World& w);
Hunt* currentHunt();

// ghost.cpp
void spawnGhost(Hunt& h);
void thinkGhost(Hunt& h, float dt);
// Throws a physics prop near the ghost now. Returns false when none is in reach.
bool ghostThrow(Hunt& h);

// overlay.cpp: debug views and the EMF reader on the HUD.
void registerOverlays();

